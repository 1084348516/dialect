const zhHant = Object.fromEntries(Object.entries(zhHans).map(([k, v]) => [k, toHant(v)])) as Record<UiKey, string>;

export const ui: Record<Lang, Record<UiKey, string>> = { 'zh-hans': zhHans, 'zh-hant': zhHant, en };

export function t(lang: Lang, key: UiKey, vars: Record<string, string | number> = {}): string {
  return ui[lang][key].replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}
